for (const loc of ['zh-CN', 'en-US', 'ru-RU'] as Locale[]) {
  Object.assign(dict[loc], extra[loc], site[loc])
}

const saved = (typeof localStorage !== 'undefined' && localStorage.getItem('yunmm_locale')) as Locale | null
export const locale = ref<Locale>(
  saved === 'zh-CN' || saved === 'ru-RU' || saved === 'en-US' ? saved : 'zh-CN',
)

if (typeof document !== 'undefined') {
  document.documentElement.lang = locale.value
}

export function setLocale(next: Locale) {
  locale.value = next
  localStorage.setItem('yunmm_locale', next)
  document.documentElement.lang = next
}

export function t(key: string): string {
  const loc = locale.value
  return dict[loc][key] ?? dict['zh-CN'][key] ?? dict['en-US'][key] ?? key
}

export function ts(prefix: string, value: unknown): string {
  const key = `${prefix}.${value}`
  const translated = t(key)
  return translated === key ? String(value ?? '') : translated
}

export function tf(key: string, vars: Record<string, string | number> = {}): string {
  return t(key).replace(/\{(\w+)\}/g, (_, name) => String(vars[name] ?? ''))
}
